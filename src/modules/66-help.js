// 66-help.js — 인게임 가이드 모달 빌더.
// 65-ui.js의 buildCodex / buildConstellation / buildSettings와 동일한 시그니처.
// panel({...}) 와 h(...) 헬퍼는 외부(65-ui.js)에서 import 되며, ctx.assets.ui가 노출.

/**
 * 인게임 도움말 모달을 빌드한다.
 * @param {object} ctx - { h, panel, closeModal } 헬퍼 묶음
 * @returns {HTMLElement} 모달 루트 노드
 */
export function buildHelp(ctx) {
  const { h, panel, closeModal } = ctx;

  const p = panel({ title: '도움말', kanji: '도움', cls: 'sk-modal wide help', close: closeModal });
  p.root.__titleId = p.titleId;
  const body = p.body;

  // 카드 단위 빌더 — th는 짙은 헤더 배경, td는 밝은 본문 배경.
  // 가독성 극대화: 본문은 흰 종이결 배경 위에 짙은 텍스트로 통일.
  const sec = (header, secBody) => {
    const w = h('section.help-sec');
    w.append(h('h2', header));
    w.append(secBody);
    body.append(w);
  };
  const tbl = (rows) => {
    const t = h('table.help-tbl');
    for (const [k, v] of rows) t.append(h('tr', h('th', k), h('td', v)));
    return t;
  };
  const para = (text) => h('p.help-p', text);
  const grid = (children) => {
    const d = h('div.help-grid');
    for (const c of children) d.append(c);
    return d;
  };
  const card = (children) => {
    const c = h('div.help-card');
    for (const ch of children) c.append(ch);
    return c;
  };

  // ── 1. 기본 ──────────────────────────────────────
  sec('1. 기본', card([
    tbl([
      ['목표', '벚꽃 나무를 키우고 정령을 모아, 시즈널 꽃을 피웁니다. 영원한 꽃에 도달하면 새로운 도감과 별자리가 열립니다.'],
      ['꽃잎', '기본 자원. 시간에 따라 자라며, 흔들기로 더 많이 받을 수 있습니다.'],
      ['흔들기', '메인 화면을 클릭(스페이스바)해 가지를 흔듭니다. 치명타(노란빛)가 나올 때 더 강합니다.'],
      ['정령', '꽃잎을 모으면 정령을 영입해 자동 꽃잎을 받을 수 있습니다.'],
      ['계절', '충분히 성장하면 새 계절을 시작해 메타 진행을 받습니다.'],
    ]),
    para('벚꽃 단계: 겨울 눈봉우리 → 봉우리 → 초咲 → 만개 → 찬란한 꽃 → 영원한 꽃. 1,000 / 100,000 / 10,000,000 / 10,000,000,000 / 10,000,000,000,000 꽃잎에서 다음 단계로 넘어갑니다.'),
  ]));

  // ── 2. 경제 시스템 ──────────────────────────────
  sec('2. 경제 시스템', card([
    tbl([
      ['정령 (10종)', '바람 정령 → 꽃잎 줍는 아이 → 무녀 → 석등롱 → 잉어의 영혼 → 달 토끼 → 여우 사자 → 풍신의 사자 → 영원한 꽃의 마음 → 하늘의 가지. 각 정령은 영구 보유되며, 자동 꽃잎을 생산합니다.'],
      ['정령 돌봄 (40개)', '정령 1개당 4단계 강화. 비용은 baseCost × [1, 8, 50, 500]. 잠금 해제: 1, 8, 25, 100마리 보유. 효과: 해당 정령의 능력치 +2.'],
      ['손 흔들기 (18개)', '직접 흔들기 강화. 닳고 닳은 손바닥, 익숙한 리듬, 벚꽃 놀이의 열기, 찰나의 만개, 오미쿠지: 대길 등. 비용 25 ~ 2×10¹⁴.'],
      ['숲 자체 (14개)', '숲 시스템 일괄 강화. 꽃잎 자석, 이슬 저장고, 폭풍 유리, 폭풍의 눈, 숲이 스스로 흔든다 등. 6×10⁴ ~ 2×10¹⁴.'],
      ['메타 보너스 (6개)', '정령 전체 보너스. 한마디 감사, 함께 쓰는 주전자, 당번표, 축제 임금, 한 가지 목적, 숲은 기억한다. 정령 15~260마리 임계값.'],
      ['별자리 (30 노드)', '5가지 가지(바람 / 물 / 달 / 돌 / 꽃)로 구성된 방사형 트리. 각 노드는 메타 진행 시 영구 능력치를 받습니다.'],
      ['도감 (12 변종)', '12가지 벚꽃 변종 발견. 각 발견 시 메타 진행 자원 보상. 변종마다 고유 능력치 (passive / click / prod).'],
      ['꽃송이 (메타 화폐)', '절대 초기화되지 않는 영구 자원. 업적, 도감 발견, 별자리 해금, 시즌 통과, 10억 꽃잎 돌파 시 획득.'],
      ['벚꽃 정수', '시즌을 돌릴 때마다 획득. 메타 진행의 핵심 자원.'],
    ]),
    para('나무심장 (HEARTWOOD) 8개 — 꽃송이 화폐로만 구매: 반지 / 손자국 / 묘판 / 주뿌리 / 부적 / 등불 / 왕관 / 증류기. 효과는 prod / click / 시작 정령 / crit / offRate / prod / essence.'),
  ]));

  // ── 3. 이벤트와 계절 ────────────────────────────
  sec('3. 이벤트와 계절', card([
    tbl([
      ['시간대', '새벽 (첫 빛) → 낮 (온갖 햇살) → 황혼 (황금시 +15%) → 밤 (보름달 +25%)이 매 24초 주기로 순환.'],
      ['이벤트 풀', '꽃보라 폭풍 (×10 꽃잎 10초) / 봄비 (+10% 30초) / 보름달 (+25% 치명타) / 황금시 (즉시 15% 흔들기) / 광란의 꽃 (×7 30초) / 연타 광란 (×77 13초) / 만개비 (1분치 일시 6초).'],
      ['황금 꽃잎', '황금시 이벤트 시 화면에 황금 페트라 흩뿌려짐. 잡으면 즉시 15% 보너스.'],
      ['치명타', '기본 3%. 노란빛 흔들기 시 ×12 효과 + 5% 추가.'],
      ['시즌', '충분히 진행하면 "새 계절" 시작 가능. 시작 시 벚꽃 정수 + 꽃송이 보너스, 메타 진행 유지.'],
    ]),
    para('이벤트는 weight(가중치) 기반으로 랜덤 발화. 풀 확률: 꽃보라 28%, 봄비 28%, 보름달 14%, 황금시 7%, 광란 11%, 연타 5%, 만개비 4%, 황금 페트라 3%.'),
  ]));

  // ── 4. 전략 팁 ──────────────────────────────────
  sec('4. 전략 팁', card([
    tbl([
      ['초반 (시즌 1)', '바람 정령 1마리 → 1단계 강화 → 자동 꽃잎 시작. 클릭으로 가속.'],
      ['중반 (정령 4종+)', '정령 돌봄을 4종 모두 2~3단계까지. 손 흔들기 3종 정도 사서 click power 확보.'],
      ['후반 (메타 진행)', 'HEARTWOOD를 꽃송이로 1~2개. 별자리 1개 분기 완전히 채우기. 도감 12개 다 모으기.'],
      ['이벤트 활용', '황금시 = click 강화. 광란 = 자동 강화. 보름달 = 일시 crit 강화. 상황별 정령 우선.'],
      ['저장', 'localStorage 자동 저장. 한 번에 며칠 동안 두면 자동 진행.'],
    ]),
    para('가장 효율적인 패턴: 손 흔들기 (소량 투자) → 정령 (자동 기반) → 정령 돌봄 (효율 증대) → 숲 자체 (시스템 강화) → 메타 진행 (별자리 / HEARTWOOD).'),
    para('꽤 알려지지 않은 팁: 황금 페트라가 보이면 즉시 잡으세요. 즉각 15% click 보너스. 5초 안에 잡지 못하면 사라집니다.'),
  ]));

  // ── 푸터 ──
  body.append(h('div.help-foot', h('em', '이 게임은 도움말의 끝. 즐거운 가꾸기!')));

  return p.root;
}
